package generator

import (
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/types"
	"iter"
	"maps"
	"slices"
	"strings"

	"golang.org/x/tools/go/packages"
)

type (
	pkgGen struct {
		pkg     *packages.Package
		imports map[string]string
		codecs  map[string]string
		decls   []string
		steps   []stepModel
	}

	codecField struct {
		attr  string
		field string
		codec string
		owner string
		typ   string
	}
)

const (
	// GeneratedFile is the file argyll-gen writes into each package
	GeneratedFile = "zz_argyll_gen.go"

	apiPackage     = "github.com/kode4food/argyll/engine/pkg/api"
	codecPackage   = "github.com/kode4food/argyll/sdk/go/codec"
	runtimePackage = "github.com/kode4food/argyll/sdk/go/gen"

	header = "// Code generated by argyll-gen. DO NOT EDIT.\n\n"
)

var ErrUnsupportedType = errors.New("unsupported attribute type")

// Render returns the generated source for a package, or nil when the
// package contains no Argyll directives
func Render(pkg *packages.Package) ([]byte, error) {
	g := &pkgGen{
		pkg:     pkg,
		imports: map[string]string{},
		codecs:  map[string]string{},
	}
	for _, f := range pkg.Syntax {
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok {
				continue
			}
			if err := g.addFunc(fn); err != nil {
				return nil, err
			}
		}
	}
	if len(g.steps) == 0 {
		return nil, nil
	}
	return g.source()
}

func (g *pkgGen) source() ([]byte, error) {
	var sb strings.Builder
	sb.WriteString(header)
	fmt.Fprintf(&sb, "package %s\n\n", g.pkg.Name)
	sb.WriteString(g.importBlock())
	for _, d := range g.decls {
		sb.WriteString(d)
		sb.WriteString("\n\n")
	}

	names := make([]string, 0, len(g.steps))
	for _, s := range g.steps {
		name := ExportedName(s.id) + "Step"
		names = append(names, name)
		sb.WriteString(g.stepVar(name, s))
		sb.WriteString("\n\n")
	}

	sb.WriteString(
		"// ArgyllSteps returns the steps generated for this package\n" +
			"func ArgyllSteps() []gen.StepDef {\nreturn []gen.StepDef{\n")
	for _, n := range names {
		fmt.Fprintf(&sb, "%s,\n", n)
	}
	sb.WriteString("}\n}\n")

	src, err := format.Source([]byte(sb.String()))
	if err != nil {
		return nil, fmt.Errorf("%w:\n%s", err, sb.String())
	}
	return src, nil
}

func (g *pkgGen) importBlock() string {
	paths := []string{apiPackage, runtimePackage, codecPackage}
	for p := range g.imports {
		if p != apiPackage && p != runtimePackage && p != codecPackage {
			paths = append(paths, p)
		}
	}
	slices.Sort(paths)

	var sb strings.Builder
	sb.WriteString("import (\n")
	for _, p := range paths {
		fmt.Fprintf(&sb, "%q\n", p)
	}
	sb.WriteString(")\n\n")
	return sb.String()
}

func (g *pkgGen) stepVar(name string, s stepModel) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "// %s exposes %s as an Argyll step\n"+
		"var %s = gen.StepDef{\n", name, s.id, name)
	fmt.Fprintf(&sb, "ID: %q,\nName: %q,\nType: %s,\n", s.id, s.name,
		s.stepType)
	sb.WriteString(labelList(s.labels))
	sb.WriteString(attrList("Inputs", s.inputs))
	sb.WriteString(attrList("Outputs", s.outputs))
	fmt.Fprintf(&sb, "Handler: %s,\n", s.handler)
	sb.WriteString("}\n")
	return sb.String()
}

func (g *pkgGen) wrapStruct(
	name string, names []string, types []types.Type,
) (string, []attrModel, error) {
	fields := make([]codecField, len(names))
	attrs := make([]attrModel, len(names))
	var decl strings.Builder
	fmt.Fprintf(&decl, "type %s struct {\n", name)
	for i, n := range names {
		expr, err := g.codecExpr(types[i])
		if err != nil {
			return "", nil, err
		}
		field := ExportedName(n)
		fmt.Fprintf(&decl, "%s %s\n", field, g.typeOf(types[i]))
		fields[i] = codecField{
			attr:  n,
			field: field,
			codec: expr,
			owner: name,
			typ:   g.typeOf(types[i]),
		}
		attrs[i] = attrModel{
			name:     n,
			attrType: attributeType(types[i]),
			optional: isPointer(types[i]),
		}
	}
	decl.WriteString("}")
	g.decls = append(g.decls, decl.String())

	codecVar := "argyllCodec" + strings.TrimPrefix(name, "argyll")
	g.decls = append(g.decls, structDecl(codecVar, name, fields))
	return codecVar, attrs, nil
}

func (g *pkgGen) codecExpr(t types.Type) (string, error) {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return g.basicCodec(t, u)
	case *types.Struct:
		return g.structCodec(t, u)
	case *types.Slice, *types.Pointer, *types.Map:
		if _, named := t.(*types.Named); named {
			return "", fmt.Errorf("%w: %s", ErrUnsupportedType, g.typeOf(t))
		}
		return g.compositeCodec(u)
	default:
		return "", fmt.Errorf("%w: %s", ErrUnsupportedType, g.typeOf(t))
	}
}

func (g *pkgGen) basicCodec(t types.Type, u *types.Basic) (string, error) {
	info := u.Info()
	switch {
	case info&types.IsString != 0:
		return fmt.Sprintf("codec.Text[%s]()", g.typeOf(t)), nil
	case info&types.IsBoolean != 0:
		return fmt.Sprintf("codec.Boolean[%s]()", g.typeOf(t)), nil
	case info&(types.IsInteger|types.IsFloat) != 0:
		return fmt.Sprintf("codec.Number[%s]()", g.typeOf(t)), nil
	default:
		return "", fmt.Errorf("%w: %s", ErrUnsupportedType, g.typeOf(t))
	}
}

func (g *pkgGen) compositeCodec(u types.Type) (string, error) {
	switch u := u.(type) {
	case *types.Slice:
		return g.wrapCodec("codec.Slice", u.Elem())
	case *types.Pointer:
		return g.wrapCodec("codec.Optional", u.Elem())
	case *types.Map:
		if b, ok := u.Key().Underlying().(*types.Basic); !ok ||
			b.Info()&types.IsString == 0 {
			return "", fmt.Errorf("%w: %s keys", ErrUnsupportedType,
				g.typeOf(u.Key()))
		}
		return g.wrapCodec("codec.Map", u.Elem())
	default:
		return "", fmt.Errorf("%w: %s", ErrUnsupportedType, g.typeOf(u))
	}
}

func (g *pkgGen) wrapCodec(fn string, elem types.Type) (string, error) {
	inner, err := g.codecExpr(elem)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%s(%s)", fn, inner), nil
}

func (g *pkgGen) structCodec(t types.Type, u *types.Struct) (string, error) {
	name := g.typeOf(t)
	if v, ok := g.codecs[name]; ok {
		return v, nil
	}
	v := g.codecName(t)
	g.codecs[name] = v

	var fields []codecField
	for f := range structFields(u) {
		expr, err := g.codecExpr(f.Type())
		if err != nil {
			return "", err
		}
		fields = append(fields, codecField{
			attr:  SnakeCase(f.Name()),
			field: f.Name(),
			codec: expr,
			owner: name,
			typ:   g.typeOf(f.Type()),
		})
	}
	g.decls = append(g.decls, structDecl(v, name, fields))
	return v, nil
}

func (g *pkgGen) codecName(t types.Type) string {
	if named, ok := t.(*types.Named); ok {
		return "argyllCodec" + named.Obj().Name()
	}
	return fmt.Sprintf("argyllCodecAnon%d", len(g.codecs))
}

func (g *pkgGen) typeOf(t types.Type) string {
	if t == nil {
		return "struct{}"
	}
	return types.TypeString(t, g.qualifier)
}

func (g *pkgGen) qualifier(p *types.Package) string {
	if p == g.pkg.Types {
		return ""
	}
	g.imports[p.Path()] = p.Name()
	return p.Name()
}

func structDecl(name, owner string, fields []codecField) string {
	if len(fields) == 0 {
		return fmt.Sprintf("var %s = codec.Struct[%s]()", name, owner)
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "var %s = codec.Struct(\n", name)
	for _, f := range fields {
		fmt.Fprintf(&sb, "codec.Field(%q, %s,\nfunc(v *%s) *%s {\n"+
			"return &v.%s\n},\n),\n", f.attr, f.codec, f.owner, f.typ,
			f.field)
	}
	sb.WriteString(")")
	return sb.String()
}

func labelList(labels map[string]string) string {
	if len(labels) == 0 {
		return ""
	}
	var sb strings.Builder
	sb.WriteString("Labels: api.Labels{\n")
	for _, k := range slices.Sorted(maps.Keys(labels)) {
		fmt.Fprintf(&sb, "%q: %q,\n", k, labels[k])
	}
	sb.WriteString("},\n")
	return sb.String()
}

func attrList(name string, attrs []attrModel) string {
	if len(attrs) == 0 {
		return ""
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "%s: []gen.Attr{\n", name)
	for _, a := range attrs {
		fmt.Fprintf(&sb, "{Name: %q, Type: %s", a.name, a.attrType)
		if a.optional {
			sb.WriteString(", Optional: true")
		}
		sb.WriteString("},\n")
	}
	sb.WriteString("},\n")
	return sb.String()
}

func attributeType(t types.Type) string {
	if p, ok := t.(*types.Pointer); ok {
		return attributeType(p.Elem())
	}
	switch u := t.Underlying().(type) {
	case *types.Basic:
		info := u.Info()
		switch {
		case info&types.IsString != 0:
			return "api.TypeString"
		case info&types.IsBoolean != 0:
			return "api.TypeBoolean"
		case info&(types.IsInteger|types.IsFloat) != 0:
			return "api.TypeNumber"
		}
	case *types.Slice:
		return "api.TypeArray"
	case *types.Struct, *types.Map:
		return "api.TypeObject"
	}
	return "api.TypeAny"
}

func structFields(s *types.Struct) iter.Seq[*types.Var] {
	return func(yield func(*types.Var) bool) {
		for f := range s.Fields() {
			if f.Exported() {
				if !yield(f) {
					return
				}
			}
		}
	}
}
